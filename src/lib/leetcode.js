function levelForCount(count) {
  if (!count) return 0
  if (count <= 3) return 1
  if (count <= 6) return 2
  if (count <= 12) return 3
  return 4
}

function normalizeSubmissions(raw) {
  if (Array.isArray(raw)) {
    return raw.map((s) => ({
      date: s.date,
      count: s.count,
      level: s.level ?? levelForCount(s.count),
    }))
  }
  const map = typeof raw === 'string' ? JSON.parse(raw) : raw
  if (!map) return []
  return Object.entries(map)
    .map(([ts, count]) => ({
      date: new Date(ts * 1000).toISOString().slice(0, 10),
      count: Number(count),
      level: levelForCount(Number(count)),
    }))
    .sort((a, b) => a.date.localeCompare(b.date))
}

export function buildLeetCodeFromFallback() {
  return {
    ...FALLBACK_LEETCODE,
    submissions: normalizeSubmissions(FALLBACK_LEETCODE.submissions),
  }
}

export async function fetchLeetCodeData() {
  const res = await fetch(
    `https://alfa-leetcode-api.onrender.com/userProfile/${LEETCODE_USERNAME}`,
  )
  if (!res.ok) throw new Error(`HTTP ${res.status}`)
  const data = await res.json()
  return {
    totalSolved: data.totalSolved ?? FALLBACK_LEETCODE.totalSolved,
    easySolved: data.easySolved ?? FALLBACK_LEETCODE.easySolved,
    mediumSolved: data.mediumSolved ?? FALLBACK_LEETCODE.mediumSolved,
    hardSolved: data.hardSolved ?? FALLBACK_LEETCODE.hardSolved,
    totalEasy: data.totalEasy ?? FALLBACK_LEETCODE.totalEasy,
    totalMedium: data.totalMedium ?? FALLBACK_LEETCODE.totalMedium,
    totalHard: data.totalHard ?? FALLBACK_LEETCODE.totalHard,
    ranking: data.ranking ?? FALLBACK_LEETCODE.ranking,
    submissions: normalizeSubmissions(data.submissionCalendar),
  }
}
